_WEIGHTS = r"""@COMMON@# Applies the port sources (incident power and phase per port) of one weight-table row to the active HFSS design. MODEL_ONLY.
# EditSources is NOT verified against an AEDT version: it is wrapped; on failure the script prints the table to type into Results > Edit Sources.
# Weights: |w|^2 = incident power in W (sum = 1 W), phase = angle(w) in degrees, the model's convention (exp(+j w t), phase referenced to each identical port plane).
THETA_DEG = 0.0      # direction of the table row to apply (nearest row is used); phi is ignored at theta 0
PHI_DEG = 0.0
TABLE = @TABLE@      # (theta, phi, [(power_W, phase_deg) for ports 1..7])
oProject = oDesktop.GetActiveProject()
oDesign = oProject.GetActiveDesign()
def note(level, text):
    try:
        oDesktop.AddMessage(oProject.GetName(), oDesign.GetName(), level, text)
    except Exception:
        pass
    try:
        sys.stdout.write(str(text) + "\n")
    except Exception:
        pass
def dist(row):
    t, p = row[0], row[1]
    a, b = math.radians(THETA_DEG), math.radians(t)
    c = math.cos(a) * math.cos(b) + math.sin(a) * math.sin(b) * math.cos(math.radians(PHI_DEG - p))
    return math.acos(max(-1.0, min(1.0, c)))
row = min(TABLE, key=dist)
ports = ["Port%d" % (k + 1) for k in range(7)]
note(0, "Row theta %g phi %g: " % (row[0], row[1]) + "; ".join("%s %.4g W %.1f deg" % (ports[k], row[2][k][0], row[2][k][1]) for k in range(7)))
try:
    sol = oDesign.GetModule("Solutions")
    sol.EditSources("PowerWatts", ["NAME:Names"] + ports,
                    ["NAME:Magnitudes"] + ["%.6gW" % row[2][k][0] for k in range(7)],
                    ["NAME:Phases"] + ["%.3fdeg" % row[2][k][1] for k in range(7)],
                    ["NAME:Terminated"], ["NAME:Resistances"], ["NAME:Reactances"])
    note(0, "Sources set. Check Results > Edit Sources before analysing.")
except Exception as exc:
    note(1, "EditSources failed (%s): set the sources by hand in Results > Edit Sources with the values above (type: Power, W, deg)." % exc)
"""


def _fill(tpl, **kw):
    out = tpl.replace("@COMMON@", _COMMON.replace("@TITLE@", kw.pop("title")))
    for k, v in kw.items():
        out = out.replace(f"@{k}@", str(v))
    return out


def aedt_build_script(cells, r_mm, name="phase29_compact7"):
    rows = ",\n    ".join(
        "({:.3f}, {:.3f}, {:.3f}, {:.3f}, {:.4f})".format(
            c["x_mm"], c["y_mm"], c["slot_L_mm"], c["slot_W_mm"], c["slot_angle_deg"]
        )
        for c in cells
    )
    wx, wy = board_size_mm(r_mm)
    feeds = "[" + ", ".join("({:.3f}, {:.3f})".format(*q[:2]) for q in tile_centres_mm(r_mm)) + "]"
    return _fill(
        _BUILD,
        title=f"compact 7-tile tensor-CP board (R {r_mm:g} mm hexagons, {len(cells)} cells)",
        NAME=name,
        H=H_MM,
        WX=f"{wx:g}",
        WY=f"{wy:g}",
        FEEDS=feeds,
        D=D_MM,
        ROWS=rows,
        MONO_H=MONO_H,
        R_PIN=R_PIN,
        R_OUT=R_OUT,
    )


def aedt_weights_script(table_rows):
    """`table_rows`: weight-table rows `{theta_deg, phi_deg, weights: [[re, im] x 7]}`."""
    body = []
    for r in table_rows:
        w = np.array([complex(a, b) for a, b in r["weights"]])
        items = ", ".join(
            f"({abs(x) ** 2:.6g}, {np.degrees(np.angle(x)) if abs(x) > 1e-9 else 0.0:.2f})" for x in w
        )
        body.append("({:g}, {:g}, [{}])".format(r["theta_deg"], r["phi_deg"], items))
    return _fill(_WEIGHTS, title="port sources from the weight table", TABLE="[\n    " + ",\n    ".join(body) + "\n]")


def write_layout(cells, r_mm, out):
    out = Path(out)
    cen = tile_centres_mm(r_mm)
    owner = [int(np.argmin([np.hypot(c["x_mm"] - q[0], c["y_mm"] - q[1]) for q in cen])) + 1 for c in cells]
    with open(out / "layout.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["x_mm", "y_mm", "circle_D_mm", "slot_L_mm", "slot_W_mm", "slot_angle_deg", "tile_port"])
        for c, o in zip(cells, owner, strict=True):
            w.writerow(
                [
                    f"{c['x_mm']:.3f}",
                    f"{c['y_mm']:.3f}",
                    D_MM,
                    f"{c['slot_L_mm']:.2f}",
                    f"{c['slot_W_mm']:.2f}",
                    f"{c['slot_angle_deg']:.3f}",
                    o,
                ]
            )
    (out / "layout.json").write_text(
        json.dumps(
            {
                "tile_radius_mm": r_mm,
                "board_mm": board_size_mm(r_mm),
                "feeds_mm": [list(q[:2]) for q in cen],
                "tile_hexagon_vertices_mm": [tile_hex_vertices(q[:2], r_mm) for q in cen],
                "cells": cells,
            },
            indent=1,
            default=float,
        ),
        encoding="utf-8",
    )
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(7, 6))
        for q in cen:
            v = tile_hex_vertices(q[:2], r_mm)
            v = np.array(v + [v[0]])
            ax.plot(v[:, 0], v[:, 1], "k-", lw=0.8)
        for c in cells:
            a = np.radians(c["slot_angle_deg"])
            h = c["slot_L_mm"] / 2
            ax.plot(
                [c["x_mm"] - h * np.cos(a), c["x_mm"] + h * np.cos(a)],
                [c["y_mm"] - h * np.sin(a), c["y_mm"] + h * np.sin(a)],
                "b-",
                lw=0.8,
            )
        for k, q in enumerate(cen):
            ax.plot(q[0], q[1], "r^")
            ax.annotate(f"P{k + 1}", (q[0], q[1]), color="r", fontsize=9, xytext=(3, 3), textcoords="offset points")
        ax.set_aspect("equal")
        ax.set_title("compact 7-tile board: ports and slot axes (MODEL_ONLY)")
        fig.savefig(out / "layout.png", dpi=110, bbox_inches="tight")
        plt.close(fig)
    except Exception:  # the PNG is a convenience only
        pass
