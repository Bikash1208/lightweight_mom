def build_script(name, d, slot, angle):
    text = TEMPLATE
    values = {
        "NAME": "slotted_" + name,
        "EPS": repr(EPS_R),
        "TAND": repr(TAND),
        "LID": "60.0",
        "D": repr(d),
        "SLOT_L": repr(slot[0]) if slot else "0.0",
        "SLOT_W": repr(slot[1]) if slot else "0.0",
        "ANGLE": repr(angle),
        "SLOTDESC": ("with a %.1f x %.1f mm slot at %g deg to x" % (slot[0], slot[1], angle)) if slot else "(no slot)",
        "PX": "%.2f" % PHASE_X,
        "PD": "%.2f" % PHASE_DIAG,
    }
    for k, v in values.items():
        text = text.replace("@@%s@@" % k, v)
    return text


def predict(mesh_n, cells):
    from src.basis_functions import MeshSettings
    from src.dispersion import tensor_sheet as ts
    sys.path.insert(0, str(ROOT / "scripts" / "research"))
    import phase26_slotted_family as sf

    out = {}
    for name, (d, slot, ang) in cells.items():
        cell = sf.make_cell("circle", d, slot[0] if slot else 0.0, slot[1] if slot else 0.0, ang)
        mesh = MeshSettings(mesh_n, mesh_n, mesh_n)
        px = np.radians(PHASE_X) / (P_MM * 1e-3)
        pdg = np.radians(PHASE_DIAG) / (P_MM * 1e-3)
        rx = ts.bloch_frequencies(cell, mesh, px, 0.0)
        rd = ts.bloch_frequencies(cell, mesh, pdg, pdg)

        def tm(rs):
            return sorted(rs, key=lambda r: (-round(r[1], 2), r[0]))[0][0]

        out[name] = {
            "f_along_x_ghz": tm(rx) / 1e9,
            "f_diagonal_ghz": tm(rd) / 1e9,
            "all_roots_along_x_ghz_tm_fraction": [[round(f / 1e9, 4), round(t, 2)] for f, t in rx],
            "all_roots_diagonal_ghz_tm_fraction": [[round(f / 1e9, 4), round(t, 2)] for f, t in rd],
        }
        print(name, mesh_n, out[name], flush=True)
    return out


