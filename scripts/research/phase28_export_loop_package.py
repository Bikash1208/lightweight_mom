def _read(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines()]


def y_of(r):
    return np.array([[complex(*c) for c in row] for row in r["y_s"]])


def gamma(y, f_hz):
    omega, k0 = angular_frequency(f_hz), free_space_wavenumber(f_hz)
    yin = y + _y_slab(0.0, omega, SUB.eps_complex, k0, SUB.thickness) * np.eye(2)
    return (Y0 * np.eye(2) - yin) @ np.linalg.inv(Y0 * np.eye(2) + yin)


def db(z):
    return 20 * math.log10(max(abs(z), 1e-300))


def deg(z):
    return math.degrees(math.atan2(z.imag, z.real))


