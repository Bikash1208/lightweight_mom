"""Phase 26 D: export the single 150 mm hexagon tensor-CP board (rotating slotted circles) for HFSS.

    python scripts/research/phase26_export_single_hex.py [cells.json results.json out_dir]

Writes `layout.json/.csv/.dxf/.png`, `board.step` (CadQuery, if available), `hfss_build_board.py` (AEDT,
native exact geometry: circle minus a slot polygon with exact rotated corners, no STEP import needed),
`predictions.json`, `README.md`. Everything the README quotes is read from the Phase 26 C results file.
"""

import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
CELLS = ROOT / "results/phase26/tensor_cp_hexagon_cells.json"
RESULTS = ROOT / "results/phase26/tensor_cp_hexagon.json"
OUT = ROOT / "hfss_exports/hex150_tensor_cp_single"
D_MM = 6.0
H_MM = 1.575
R_HEX = 150.0
BOARD_X, BOARD_Y = 270.0, 310.0  # hexagon bounding box 259.81 x 300 mm + 5 mm margin


def slot_corners(x, y, length, width, angle_deg):
    a = np.radians(angle_deg)
    c, s = np.cos(a), np.sin(a)
    pts = []
    for u, v in ((-length / 2, -width / 2), (length / 2, -width / 2), (length / 2, width / 2), (-length / 2, width / 2)):
        pts.append((round(x + u * c - v * s, 4), round(y + u * s + v * c, 4)))
    return pts


def hexagon_vertices():
    return [(round(R_HEX * np.cos(np.radians(90 + 60 * i)), 3), round(R_HEX * np.sin(np.radians(90 + 60 * i)), 3)) for i in range(6)]


def aedt_script(cells, mono_h="2.794mm", r_pin="0.305mm"):
    rows = ",\n    ".join("(%.3f, %.3f, %.3f, %.3f, %.4f)" % (c["x_mm"], c["y_mm"], c["slot_L_mm"], c["slot_W_mm"], c["slot_angle_deg"]) for c in cells)
    return f'''# -*- coding: utf-8 -*-
# HFSS (AEDT) IronPython script -- single 150 mm hexagon tensor-CP board "hex150_tensor_cp_single" (generated by lwmom, Phase 26 D).
# Run inside AEDT: Tools > Run Script...  Native exact geometry, mm; no STEP import.
#
#   Substrate  eps_r 2.2, tan d 0.0009 (RT/duroid 5880), {BOARD_X:g} x {BOARD_Y:g} x {H_MM} mm, z = 0 .. {H_MM} mm, centred on the feed
#   Ground     PEC sheet at z = 0 with a coax opening (radius r_out)
#   Cells      {len(cells)} slotted circular patches (D {D_MM} mm; slot L x W and angle per cell) at z = {H_MM} mm, Perfect E
#   Monopole   PEC pin radius r_pin, height mono_h from the ground, lumped 50 ohm port on the coax annulus at z = 0
#   Air        padded box, radiation boundary; far-field sphere theta 0..180, phi 0..360, 1 deg
# FEED: mono_h = 110 mil (2.794 mm) and r_pin = 12 mil (0.305 mm) are the HFSS variables of the hex150_gap0 run
# (hfss_results/hex150_gap0). The real pin height above ground is still to be confirmed; the old exporter default was 7.1 mm.
import math
import ScriptEnv
ScriptEnv.Initialize("Ansoft.ElectronicsDesktop")
oDesktop.RestoreWindow()
oProject = oDesktop.NewProject()
oProject.InsertDesign("HFSS", "hex150_tensor_cp_single", "DrivenModal", "")
oDesign = oProject.SetActiveDesign("hex150_tensor_cp_single")
oEditor = oDesign.SetActiveEditor("3D Modeler")
oEditor.SetModelUnits(["NAME:Units Parameter", "Units:=", "mm", "Rescale:=", False])
ADD_SWEEP = True
H = "{H_MM}mm"
WX = "{BOARD_X:g}mm"; WY = "{BOARD_Y:g}mm"
FEED = (0.0, 0.0)
D = {D_MM}
CELLS = [  # (x, y, slot length, slot width, slot angle deg) mm; slot centred on the circle, long axis at the angle from +x
    {rows}
]
oProject.GetDefinitionManager().AddMaterial(["NAME:HMSA_substrate", "CoordinateSystemType:=", "Cartesian",
    "BulkOrSurfaceType:=", 1, ["NAME:PhysicsTypes", "set:=", ["Electromagnetic"]],
    "permittivity:=", "2.2", "dielectric_loss_tangent:=", "0.0009"])
def var(name, value):
    oDesign.ChangeProperty(["NAME:AllTabs", ["NAME:LocalVariableTab", ["NAME:PropServers", "LocalVariables"],
        ["NAME:NewProps", ["NAME:" + name, "PropType:=", "VariableProp", "UserDef:=", True, "Value:=", value]]]])
for n, v in (("mono_h", "{mono_h}"), ("r_pin", "{r_pin}"), ("r_out", "2.05mm"), ("pad_xy", "15mm"), ("pad_top", "30mm"), ("pad_bot", "15mm")):
    var(n, v)
def attrs(name, material, solve_inside, color="(255 128 0)", transp=0):
    return ["NAME:Attributes", "Name:=", name, "Flags:=", "", "Color:=", color, "Transparency:=", transp,
            "PartCoordinateSystem:=", "Global", "UDMId:=", "", "MaterialValue:=", '"' + material + '"',
            "SurfaceMaterialValue:=", '""', "SolveInside:=", solve_inside, "IsMaterialEditable:=", True,
            "UseMaterialAppearance:=", False, "IsLightweight:=", False]
def mm(v):
    return repr(float(v)) + "mm"
def rect(name, x, y, z, w, h, color="(255 128 0)"):
    oEditor.CreateRectangle(["NAME:RectangleParameters", "IsCovered:=", True, "XStart:=", x, "YStart:=", y, "ZStart:=", z,
        "Width:=", w, "Height:=", h, "WhichAxis:=", "Z"], attrs(name, "vacuum", True, color))
def circle(name, x, y, z, r, color="(255 128 0)"):
    oEditor.CreateCircle(["NAME:CircleParameters", "IsCovered:=", True, "XCenter:=", x, "YCenter:=", y, "ZCenter:=", z,
        "Radius:=", r, "WhichAxis:=", "Z", "NumSegments:=", "0"], attrs(name, "vacuum", True, color))
def subtract(blank, tools, keep):
    oEditor.Subtract(["NAME:Selections", "Blank Parts:=", blank, "Tool Parts:=", ",".join(tools)],
                     ["NAME:SubtractParameters", "KeepOriginals:=", keep])
def poly_sheet(name, pts, z):
    oEditor.CreatePolyline(["NAME:PolylineParameters", "IsPolylineCovered:=", True, "IsPolylineClosed:=", True,
        ["NAME:PolylinePoints"] + [["NAME:PLPoint", "X:=", mm(x), "Y:=", mm(y), "Z:=", z] for (x, y) in pts + [pts[0]]],
        ["NAME:PolylineSegments"] + [["NAME:PLSegment", "SegmentType:=", "Line", "StartIndex:=", k, "NoOfPoints:=", 2] for k in range(len(pts))],
        ["NAME:PolylineXSection", "XSectionType:=", "None", "XSectionOrient:=", "Auto", "XSectionWidth:=", "0mm",
         "XSectionTopWidth:=", "0mm", "XSectionHeight:=", "0mm", "XSectionNumSegments:=", "0", "XSectionBendType:=", "Corner"]],
        attrs(name, "vacuum", True))
x_lo = "(-" + WX + "/2)"; y_lo = "(-" + WY + "/2)"
oEditor.CreateBox(["NAME:BoxParameters", "XPosition:=", x_lo, "YPosition:=", y_lo, "ZPosition:=", "0mm",
    "XSize:=", WX, "YSize:=", WY, "ZSize:=", H], attrs("Substrate", "HMSA_substrate", True, "(0 128 0)", 0.6))
rect("Ground", x_lo, y_lo, "0mm", WX, WY, "(128 128 128)")
oBnd = oDesign.GetModule("BoundarySetup")
oEditor.CreateCylinder(["NAME:CylinderParameters", "XCenter:=", mm(FEED[0]), "YCenter:=", mm(FEED[1]), "ZCenter:=", "0mm",
    "Radius:=", "r_pin", "Height:=", "mono_h", "WhichAxis:=", "Z", "NumSides:=", "0"], attrs("Monopole1", "pec", False, "(255 255 0)"))
circle("Hole1", mm(FEED[0]), mm(FEED[1]), "0mm", "r_out")
circle("PortSheet1", mm(FEED[0]), mm(FEED[1]), "0mm", "r_out")
circle("PinCut1", mm(FEED[0]), mm(FEED[1]), "0mm", "r_pin")
subtract("PortSheet1", ["PinCut1"], False)
subtract("Ground", ["Hole1"], False)
subtract("Substrate", ["Monopole1"], True)
oBnd.AssignLumpedPort(["NAME:Port1", "Objects:=", ["PortSheet1"], "DoDeembed:=", False, "RenormalizeAllTerminals:=", True,
    ["NAME:Modes", ["NAME:Mode1", "ModeNum:=", 1, "UseIntLine:=", True,
        ["NAME:IntLine", "Start:=", [mm(FEED[0]) + "+r_pin", mm(FEED[1]), "0mm"], "End:=", [mm(FEED[0]) + "+r_out", mm(FEED[1]), "0mm"]],
        "AlignmentGroup:=", 0, "CharImp:=", "Zpi", "RenormImp:=", "50ohm"]],
    "ShowReporterFilter:=", False, "ReporterFilter:=", [True], "Impedance:=", "50ohm"])
names = []
for k, (cx, cy, L, W, ang) in enumerate(CELLS):
    nm = "C%d" % k
    circle(nm, mm(cx), mm(cy), H, mm(D / 2.0))
    a = math.radians(ang); c = math.cos(a); s = math.sin(a)
    pts = [(round(cx + u * c - v * s, 4), round(cy + u * s + v * c, 4))
           for (u, v) in ((-L / 2, -W / 2), (L / 2, -W / 2), (L / 2, W / 2), (-L / 2, W / 2))]
    poly_sheet("S%d" % k, pts, H)
    subtract(nm, ["S%d" % k], False)
    names.append(nm)
oBnd.AssignPerfectE(["NAME:PerfE_Ground", "Objects:=", ["Ground"], "InfGroundPlane:=", False])
oBnd.AssignPerfectE(["NAME:PerfE_Patches", "Objects:=", names, "InfGroundPlane:=", False])
oEditor.CreateBox(["NAME:BoxParameters", "XPosition:=", x_lo + "-pad_xy", "YPosition:=", y_lo + "-pad_xy", "ZPosition:=", "-pad_bot",
    "XSize:=", WX + "+2*pad_xy", "YSize:=", WY + "+2*pad_xy", "ZSize:=", "pad_bot+" + H + "+pad_top"],
    attrs("Air", "air", True, "(143 175 143)", 0.9))
oBnd.AssignRadiation(["NAME:Rad1", "Objects:=", ["Air"], "IsFssReference:=", False, "IsForPML:=", False])
oAna = oDesign.GetModule("AnalysisSetup")
oAna.InsertSetup("HfssDriven", ["NAME:Setup1", "Frequency:=", "10.54GHz", "MaxDeltaS:=", 0.02, "MaximumPasses:=", 15,
    "MinimumPasses:=", 2, "MinimumConvergedPasses:=", 2, "PercentRefinement:=", 30, "IsEnabled:=", True, "BasisOrder:=", 1,
    "DoLambdaRefine:=", True, "DoMaterialLambda:=", True, "SetLambdaTarget:=", False, "Target:=", 0.3333, "UseMaxTetIncrease:=", False])
if ADD_SWEEP:
    oAna.InsertFrequencySweep("Setup1", ["NAME:Sweep", "IsEnabled:=", True, "RangeType:=", "LinearStep", "RangeStart:=", "10.01GHz",
        "RangeEnd:=", "11.07GHz", "RangeStep:=", "0.02GHz", "Type:=", "Interpolating", "SaveFields:=", False, "SaveRadFields:=", False,
        "InterpTolerance:=", 0.5, "InterpMaxSolns:=", 250, "InterpMinSolns:=", 0, "InterpMinSubranges:=", 1])
oRad = oDesign.GetModule("RadField")
oRad.InsertFarFieldSphereSetup(["NAME:3D", "UseCustomRadiationSurface:=", False, "ThetaStart:=", "0deg", "ThetaStop:=", "180deg",
    "ThetaStep:=", "1deg", "PhiStart:=", "-180deg", "PhiStop:=", "180deg", "PhiStep:=", "1deg", "UseLocalCS:=", False])
oEditor.FitAll()
oProject.SaveAs(oDesktop.GetProjectDirectory() + "/hex150_tensor_cp_single.aedt", True)
oDesktop.AddMessage(oProject.GetName(), "hex150_tensor_cp_single", 0, "Built: %d slotted-circle cells, 1 monopole, 1 lumped port. Validate, then Analyze All." % len(CELLS))
'''


def write_all(cells_path=CELLS, results_path=RESULTS, out=OUT):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    c = json.loads(Path(cells_path).read_text())
    res = json.loads(Path(results_path).read_text())
    cells = [
        {"x_mm": c["x_mm"][i], "y_mm": c["y_mm"][i], "slot_L_mm": c["slot_L_mm"][i], "slot_W_mm": c["slot_W_mm"][i],
         "slot_angle_deg": c["slot_angle_deg"][i], "alpha_np_per_m": c["alpha_np_per_m"][i]} for i in range(len(c["x_mm"]))
    ]
    (out / "hfss_build_board.py").write_text(aedt_script(cells))
    (out / "layout.json").write_text(json.dumps({"units": "mm", "diameter_mm": D_MM, "hexagon_vertices_mm": hexagon_vertices(),
                                                 "feed_mm": [0.0, 0.0], "board_mm": [BOARD_X, BOARD_Y, H_MM], "cells": cells}, indent=1))
    with open(out / "layout.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["x_mm", "y_mm", "diameter_mm", "slot_length_mm", "slot_width_mm", "slot_angle_deg"])
        for k in cells:
            w.writerow([f"{k['x_mm']:.3f}", f"{k['y_mm']:.3f}", D_MM, f"{k['slot_L_mm']:.2f}", f"{k['slot_W_mm']:.2f}", f"{k['slot_angle_deg']:.3f}"])
    try:
        import ezdxf

        doc = ezdxf.new("R2010")
        doc.layers.add("PATCH")
        doc.layers.add("SLOT")
        doc.layers.add("OUTLINE")
        msp = doc.modelspace()
        for k in cells:
            msp.add_circle((k["x_mm"], k["y_mm"]), D_MM / 2, dxfattribs={"layer": "PATCH"})
            msp.add_lwpolyline(slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"]), close=True,
                               dxfattribs={"layer": "SLOT"})
        msp.add_lwpolyline(hexagon_vertices(), close=True, dxfattribs={"layer": "OUTLINE"})
        doc.saveas(out / "layout.dxf")
    except Exception as exc:  # noqa: BLE001
        (out / "layout.dxf.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n")
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(8, 8.5))
        for k in cells:
            ax.add_patch(plt.Circle((k["x_mm"], k["y_mm"]), D_MM / 2, fc="#d9a441", ec="none"))
            p = slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"])
            ax.add_patch(plt.Polygon(p, fc="white", ec="none"))
        hv = hexagon_vertices()
        ax.add_patch(plt.Polygon(hv, fc="none", ec="k", ls="--"))
        ax.plot([0], [0], "r+", ms=12)
        ax.set_aspect("equal")
        ax.set_xlim(-140, 140)
        ax.set_ylim(-160, 160)
        ax.set_title("hex150_tensor_cp_single: %d slotted circles (D %.1f mm), feed +" % (len(cells), D_MM))
        fig.savefig(out / "layout.png", dpi=110)
    except Exception as exc:  # noqa: BLE001
        (out / "layout.png.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n")
    try:
        import cadquery as cq

        solids = None
        for k in cells:
            disk = cq.Workplane("XY").workplane(offset=H_MM).center(k["x_mm"], k["y_mm"]).circle(D_MM / 2).extrude(0.035)
            pts = slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"])
            cut = cq.Workplane("XY").workplane(offset=H_MM - 0.01).polyline(pts).close().extrude(0.06)
            cell = disk.cut(cut)
            solids = cell if solids is None else solids.add(cell)
        comp = cq.Compound.makeCompound([o for o in solids.vals()])
        cq.exporters.export(cq.Workplane("XY").add(comp), str(out / "board.step"))
    except Exception as exc:  # noqa: BLE001
        (out / "board.step.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n")
    sel = res["selected"]
    pred = {
        "labels": res["labels"], "state": "PREDICTION_NOT_HFSS_VALIDATED",
        "beam_target_theta_phi_deg": [30.0, 225.0], "frequency_ghz": 10.54,
        "selected_design": {k: sel[k] for k in ("hand", "eta_design", "taper_c", "eta_conv", "eta_conv_by_ray_min_max")},
        "aperture_pattern": sel["metrics_ap"],
        "realized_gain_rhcp_dbi": {"launch_bare_0.592": sel["gain_rhcp_dbi_launch_bare"], "launch_loaded_0.66_to_0.88": sel["gain_rhcp_dbi_launch_loaded"]},
        "accepted_power_budget": res["accepted_power_budget"],
        "ideal_polarization_compensation_upper_bound": res["ideal_polarization_compensation"]["metrics_ap"],
        "frequencies_10p33_10p75": "NOT_AVAILABLE_FROM_CURRENT_DATA (supercell table is at 10.54 GHz only)",
    }
    (out / "predictions.json").write_text(json.dumps(pred, indent=1, default=float))
    return cells, sel, res


if __name__ == "__main__":
    a = sys.argv[1:]
    write_all(*(a[:3] if len(a) >= 3 else ()))
