"""Phase 29 compact 7-tile board: AEDT build script (7 hexagonal tiles side by side, one monopole + lumped port each, slotted-circle tensor-CP cells),
`set_weights.py` (port sources from the weight table) and layout files. MODEL_ONLY: nothing here is HFSS-validated.

AEDT calls are the Phase 26 ones that ran in AEDT (substrate/ground/pin/lumped port/slotted circles/radiation box/setup/far-field sphere, as in
`hex150_tensor_cp_single`); everything new or unverified (`EditSources`, the optional sweep, the far-field setup) is wrapped, never fatal, and prints
what to do by hand. Design names are never hard-coded after creation: the actual name is read back with `oDesign.GetName()`."""

import csv
import json
from pathlib import Path

import numpy as np

from ..hologram.seven_hex_cluster import tile_centres_mm

D_MM, H_MM = 6.0, 1.575
MONO_H, R_PIN, R_OUT = (
    "7.575mm",
    "0.635mm",
    "2.05mm",
)  # pin top 6.0 mm above the surface, project pin radius, coax annulus (Phase 26)
MARGIN_MM = 5.0


def tile_hex_vertices(c, r_mm):
    return [
        (c[0] + r_mm * np.cos(np.radians(90 + 60 * i)), c[1] + r_mm * np.sin(np.radians(90 + 60 * i))) for i in range(6)
    ]


def board_size_mm(r_mm):
    v = np.array([p for q in tile_centres_mm(r_mm) for p in tile_hex_vertices(q[:2], r_mm)])
    return float(2 * (np.abs(v[:, 0]).max() + MARGIN_MM)), float(2 * (np.abs(v[:, 1]).max() + MARGIN_MM))


