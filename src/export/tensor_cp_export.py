def slot_corners(x, y, length, width, angle_deg):
    a = np.radians(angle_deg)
    c, s = np.cos(a), np.sin(a)
    pts = []
    for u, v in (
        (-length / 2, -width / 2),
        (length / 2, -width / 2),
        (length / 2, width / 2),
        (-length / 2, width / 2),
    ):
        pts.append((round(x + u * c - v * s, 4), round(y + u * s + v * c, 4)))
    return pts


def hexagon_vertices():
    return [
        (round(R_HEX * np.cos(np.radians(90 + 60 * i)), 3), round(R_HEX * np.sin(np.radians(90 + 60 * i)), 3))
        for i in range(6)
    ]


