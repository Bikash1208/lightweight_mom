"""Phase 12C markdown report."""


def render_phase12c_report_md(result):
    lines = []
    a = lines.append
    a("# Phase 12C report — does local periodicity hold for the grounded 8 mm reflectarray cell?")
    a("")
    a("Generated by `examples/run_phase12c.py` / `src/phase12c/run.py`. No ML anywhere in this "
      "phase: every number is a direct MoM solve of a real (grounded or, for Task D, the earlier "
      "phases' own ungrounded) heterogeneous supercell through the unmodified "
      "`solver.assemble_system`/`solve` pipeline, or a closed-form mesh-alignment/gate computation.")
    a("")
    a("## 1. Final statuses")
    a("")
    a("```")
    a(f"Task A (grounded supercells):       {result.task_a_status}")
    a(f"Task B (local periodicity):         {result.task_b_gate.status}")
    a(f"  {result.task_b_gate.reason}")
    a(f"Task C (coupling extent):           {result.task_c_status}")
    a(f"Task D (fine-mesh spot-check):      {result.task_d_gate.status}")
    a(f"Task E (HFSS-ready exports):        {result.hfss_export_status}")
    a(f"HFSS status:                        HFSS_NOT_AVAILABLE   (unchanged)")
    a(f"Geometry inversion:  GEOMETRY_INVERSION_LOCKED")
    a(f"STEP export:         STEP_EXPORT_LOCKED")
    a("```")
    a("")
    a("## 2. Task A: grounded supercells")
    a("")
    a(f"Homogeneous-supercell correctness proof (n={result.correctness.n}, "
      f"{result.correctness.mesh_cells_per_subcell} cells/subcell, L=W=4.0 mm, floquet_order = "
      f"2 x total mesh cells): relative error **{result.correctness.relative_error:.3e}** -- "
      f"matches Phase 9's own ~4e-15 machine-precision figure, confirming the "
      f"`GroundedSupercellUnitCell` wrapper introduces no numerical error of its own.")
    a("")
    a("Mesh-convergence series (same homogeneous case, successively doubled cells/subcell):")
    a("")
    a("| cells/subcell | relative difference from previous |")
    a("|---|---|")
    for c in result.convergence_series:
        a(f"| {c.finer_mesh_cells_per_subcell} | {c.relative_difference:.4f} |")
    a("")
    a("Largest feasible supercell size (same homogeneous case, aligned 20-cell/subcell mesh, "
      "floquet_order = 2 x total mesh cells, the validated convention):")
    a("")
    a("| n | n_unknowns | runtime [s] |")
    a("|---|---|---|")
    for p in result.feasibility_points:
        a(f"| {p.n} | {p.n_unknowns_embedded} | {p.runtime_s:.1f} |")
    a("")
    a("## 3. Task B: local-periodicity test, grounded 8 mm")
    a("")
    a("Reference reflection-phase curve (S11_xx, aligned 20-cell/subcell mesh):")
    a("")
    a("| L [mm] | \\|S11\\| | phase [deg] |")
    a("|---|---|---|")
    for p in result.curve:
        a(f"| {p.l_mm} | {p.s11_mag:.6f} | {p.s11_phase_deg:.2f} |")
    a("")
    a(f"Centres: off-resonance L={result.centers.off_resonance.l_mm} mm, "
      f"near-resonance L={result.centers.near_resonance.l_mm} mm, "
      f"at-resonance L={result.centers.at_resonance.l_mm} mm (all chosen from the measured curve "
      f"above, never assumed).")
    a("")
    a("Smooth-gradient / strong-contrast cases:")
    a("")
    a("| case | achieved step [deg] | relative complex error | phase error [deg] | within tolerance |")
    a("|---|---|---|---|---|")
    for name, step, perr, db, within in result.task_b_gate.per_case:
        a(f"| {name} | {step:.1f} | -- | {perr:.2f} | {'yes' if within else 'no'} |")
    a("")
    a(f"Gate: **{result.task_b_gate.status}** -- {result.task_b_gate.reason}")
    a("")
    a(f"Periodic phase-gradient supercell: {len(result.periodic_results)} cells, achieved span "
      f"**{result.periodic_span_deg:.1f} deg** (full 2π: {result.periodic_is_full_2pi}).")
    a("")
    a("## 4. Task C: coupling extent, grounded")
    a("")
    a("| series | convergence status | last shell increment (relative) |")
    a("|---|---|---|")
    for name, report in result.coupling_reports.items():
        a(f"| {name} | {report.convergence.status} | {report.convergence.last_increment_relative:.3e} |")
    a("")
    a("## 5. Task D: spot-check on a finer aligned mesh (read-only)")
    a("")
    for name, verdict, detail in result.task_d_gate.findings:
        a(f"- **{name}**: {verdict} -- {detail}")
    a("")
    a("## 6. Task E: HFSS-ready exports")
    a("")
    a(f"{len(result.single_cell_exports)} single-cell STEP exports, {len(result.supercell_exports)} "
      f"supercell STEP exports, synthetic one-port HFSS CSV ingestion test: "
      f"**{result.hfss_export_status}**. No real HFSS results exist anywhere in this project.")
    a("")
    a("## 7. Recommendation for Phase 13's forward model")
    a("")
    a(result.recommendation)
    a("")
    a("## 8. Rules followed")
    a("")
    a("Measured numbers only; synthetic data (Task E's HFSS ingestion test) labelled as such; no "
      "earlier phase's code or results were modified (Task D writes only under "
      "`results/phase12c_*`); no ML/fitted surrogate in the locality/coupling study (Phase 11's own "
      "rule, reused); period/geometry choices are justified, not picked by phase coverage alone.")
    return "\n".join(lines) + "\n"
