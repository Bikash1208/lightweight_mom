def write_single_board(cells, out, predictions, name="hex150_tensor_cp_single", note="", step=True):
    """Writes `hfss_build_board.py`, `layout.json/.csv/.dxf/.png`, `board.step` (if `step` and CadQuery) and `predictions.json`."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "hfss_build_board.py").write_text(aedt_script(cells, name=name, note=note), encoding="utf-8", newline="\n")
    (out / "layout.json").write_text(
        json.dumps(
            {
                "units": "mm",
                "diameter_mm": D_MM,
                "hexagon_vertices_mm": hexagon_vertices(),
                "feed_mm": [0.0, 0.0],
                "board_mm": [BOARD_X, BOARD_Y, H_MM],
                "cells": cells,
            },
            indent=1,
        )
    , encoding="utf-8", newline="\n")
    with open(out / "layout.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["x_mm", "y_mm", "diameter_mm", "slot_length_mm", "slot_width_mm", "slot_angle_deg", "cross_slot"])
        for k in cells:
            w.writerow(
                [
                    f"{k['x_mm']:.3f}",
                    f"{k['y_mm']:.3f}",
                    D_MM,
                    f"{k['slot_L_mm']:.2f}",
                    f"{k['slot_W_mm']:.2f}",
                    f"{k['slot_angle_deg']:.3f}",
                    int(k.get("cross", 0)),
                ]
            )
    try:
        import ezdxf

        doc = ezdxf.new("R2010")
        doc.layers.add("PATCH")
        doc.layers.add("SLOT")
        doc.layers.add("OUTLINE")
        msp = doc.modelspace()
        for k in cells:
            msp.add_circle((k["x_mm"], k["y_mm"]), D_MM / 2, dxfattribs={"layer": "PATCH"})
            for extra in (0.0, 90.0) if k.get("cross") else (0.0,):
                msp.add_lwpolyline(
                    slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"] + extra),
                    close=True,
                    dxfattribs={"layer": "SLOT"},
                )
        msp.add_lwpolyline(hexagon_vertices(), close=True, dxfattribs={"layer": "OUTLINE"})
        doc.saveas(out / "layout.dxf")
    except Exception as exc:  # noqa: BLE001
        (out / "layout.dxf.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n", encoding="utf-8", newline="\n")
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(8, 8.5))
        for k in cells:
            ax.add_patch(plt.Circle((k["x_mm"], k["y_mm"]), D_MM / 2, fc="#d9a441", ec="none"))
            for extra in (0.0, 90.0) if k.get("cross") else (0.0,):
                p = slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"] + extra)
                ax.add_patch(plt.Polygon(p, fc="white", ec="none"))
        hv = hexagon_vertices()
        ax.add_patch(plt.Polygon(hv, fc="none", ec="k", ls="--"))
        ax.plot([0], [0], "r+", ms=12)
        ax.set_aspect("equal")
        ax.set_xlim(-140, 140)
        ax.set_ylim(-160, 160)
        ax.set_title(f"hex150_tensor_cp_single: {len(cells)} slotted circles (D {D_MM:.1f} mm), feed +")
        fig.savefig(out / "layout.png", dpi=110)
    except Exception as exc:  # noqa: BLE001
        (out / "layout.png.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n", encoding="utf-8", newline="\n")
    try:
        if not step:
            raise RuntimeError("STEP not requested")
        import cadquery as cq

        solids = None
        for k in cells:
            disk = (
                cq.Workplane("XY").workplane(offset=H_MM).center(k["x_mm"], k["y_mm"]).circle(D_MM / 2).extrude(0.035)
            )
            cell = disk
            for extra in (0.0, 90.0) if k.get("cross") else (0.0,):
                pts = slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"] + extra)
                cut = cq.Workplane("XY").workplane(offset=H_MM - 0.01).polyline(pts).close().extrude(0.06)
                cell = cell.cut(cut)
            solids = cell if solids is None else solids.add(cell)
        comp = cq.Compound.makeCompound([o for o in solids.vals()])
        cq.exporters.export(cq.Workplane("XY").add(comp), str(out / "board.step"))
    except Exception as exc:  # noqa: BLE001
        (out / "board.step.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n", encoding="utf-8", newline="\n")
    (out / "predictions.json").write_text(json.dumps(predictions, indent=1, default=float), encoding="utf-8", newline="\n")
    return cells


