def build_script(d, cell_list):
    xs = [abs(c[1]) for c in cell_list] + [HEX_R]
    wx = 2 * (max(c[1] for c in cell_list) + SO / 2 + 5.0)
    wy = 2 * (max(abs(c[2]) for c in cell_list) + SO / 2 + 5.0)
    rep = {
        "__H__": repr(H_MM), "__TD__": repr(round(d["Td"], 3)), "__SR__": repr(round(d["s_reflector"], 3)), "__TR__": repr(round(d["T_reflector"], 3)),
        "__S1__": repr(round(d["s_dir1"], 3)), "__T1__": repr(round(d["T_dir1"], 3)), "__S2__": repr(round(d["s_dir2"], 3)), "__T2__": repr(round(d["T_dir2"], 3)),
        "__SO__": repr(SO), "__WR__": repr(WR), "__GAP__": repr(GAP), "__PITCH__": repr(PITCH), "__CELLS__": lit(cell_list), "__KEEP__": repr(KEEPOUT), "__WX__": repr(round(wx, 2)), "__WY__": repr(round(wy, 2)),
    }
    s = TEMPLATE
    for k, v in rep.items():
        s = s.replace(k, v)
    return HEAD + s


def main():
    d = json.loads(MODEL.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    cl = cells()
    (OUT / "build_launcher.py").write_text(harden(build_script(d["design_mm"], cl)), encoding="utf-8")
    with (OUT / "mom_reference_pattern.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["azimuth_deg", "tm0_power_db_calibration_A", "tm0_power_db_calibration_B"])
        a, b = (d["evaluated_under"][k]["pattern_db"] for k in d["evaluated_under"])
        for i in range(360):
            psi = i if i <= 180 else i - 360
            w.writerow([psi, f"{a[i]:.2f}", f"{b[i]:.2f}"])
    with (OUT / "mom_reference_s11.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["f_ghz", "calibration", "s11_db", "hpbw_deg", "front_to_back_db", "launch_fraction"])
        for k, sweep in d["freq_sweep"].items():
            for f, v in sweep.items():
                w.writerow([f, k[:1], f"{v['s11_db']:.2f}", f"{v['hpbw_deg']:.0f}", f"{v['front_to_back_db']:.2f}", f"{v['launch_fraction']:.3f}"])
    (OUT / "README.md").write_text(readme(d, len(cl)), encoding="utf-8")
    print("written; cells", len(cl))


