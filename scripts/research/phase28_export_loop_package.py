def rot(y, psi_deg):
    a = math.radians(psi_deg)
    r = np.array([[math.cos(a), -math.sin(a)], [math.sin(a), math.cos(a)]])
    return r @ y @ r.T


def collect():
    """{(state label, mesh, f_hz, scale-json): Y} from the measured-diode solves."""
    out = {}
    for path in (MEAS, MEAS_EXTRA):
        if Path(path).exists():
            for r in _read(path):
                out[(r["state"], r["mesh"], r["f_hz"], json.dumps(r["scale"], sort_keys=True))] = y_of(r)
    return out


def _g_rows(label_on, label_off, y, mesh, f, rot_deg=0, tag=""):
    rows = []
    for st, lab in (("ON", label_on), ("OFF", label_off)):
        yy = y[(lab, mesh, f, "null")]
        if rot_deg:
            yy = rot(yy, rot_deg)
        g = gamma(yy, f)
        ent = {"S_xx": g[0, 0], "S_yy": g[1, 1], "S_xy": g[0, 1]}
        for p in PSIS:
            a = math.radians(p)
            e, ep = np.array([math.cos(a), math.sin(a)]), np.array([-math.sin(a), math.cos(a)])
            ent[f"co_psi{p}"] = complex(e @ g @ e)
            ent[f"cross_psi{p}"] = complex(ep @ g @ e)
        for q, z in ent.items():
            rows.append((tag, st, rot_deg, f / 1e9, mesh, q, db(z), deg(z)))
    return rows


def _db_psi(a, b, p):
    e = np.array([math.cos(math.radians(p)), math.sin(math.radians(p))])
    return abs((e @ (a - b) @ e).imag) * 1e3


def reference(y):
    """Prediction rows for the HFSS-representable diode (R only / C only), 10 mA, 9.5 - 10.5 GHz at mesh 60 (mesh 90 at 10 GHz), the full-Z(f) measured diode at 10 GHz for comparison, and the tensor-rotated 20 deg cell."""
    pred = []
    for f in (9.5e9, 9.75e9, 10e9, 10.25e9, 10.5e9):
        if ("ON_10mA_Ronly", 60, f, "null") in y:
            pred += _g_rows("ON_10mA_Ronly", "OFF_0V_Conly", y, 60, f, 0, "HFSS_R10mA_Conly")
    if ("ON_10mA_Ronly", 90, 10e9, "null") in y:
        pred += _g_rows("ON_10mA_Ronly", "OFF_0V_Conly", y, 90, 10e9, 0, "HFSS_R10mA_Conly")
    pred += _g_rows("ON_5mA_Ronly", "OFF_0V_Conly", y, 60, 10e9, 0, "HFSS_R5mA_Conly")
    pred += _g_rows("ON_10mA", "OFF_0V", y, 90, 10e9, 0, "FULLZ_10mA")
    pred += _g_rows("ON_10mA_Ronly", "OFF_0V_Conly", y, 60, 10e9, 20, "TENSOR_ROTATED_20deg_R10mA_Conly")
    summ = {}
    for name, (on, off) in {"10mA": HFSS_STATES["10mA"], "5mA": HFSS_STATES["5mA"], "10mA_fullZ": ("ON_10mA", "OFF_0V"), "5mA_fullZ": ("ON_5mA", "OFF_0V")}.items():
        for mesh in (60, 90):
            if (on, mesh, 10e9, "null") in y and (off, mesh, 10e9, "null") in y:
                a, b = y[(on, mesh, 10e9, "null")], y[(off, mesh, 10e9, "null")]
                summ[f"{name}_mesh{mesh}"] = {
                    "b_bar_xx_ms": 0.5 * (a[0, 0].imag + b[0, 0].imag) * 1e3,
                    "dB_xx_ms": abs(a[0, 0].imag - b[0, 0].imag) * 1e3,
                    "dB_yy_ms": abs(a[1, 1].imag - b[1, 1].imag) * 1e3,
                    "aniso_on_ms": (a[0, 0].imag - a[1, 1].imag) * 1e3,
                    "aniso_off_ms": (b[0, 0].imag - b[1, 1].imag) * 1e3,
                    "dB_along_psi_ms": {str(p): _db_psi(a, b, p) for p in PSIS},
                }
    return pred, summ


def bare_slab():
    out = []
    for f in (9.5, 9.75, 10.0, 10.25, 10.5):
        y = _y_slab(0.0, angular_frequency(f * 1e9), SUB.eps_complex, free_space_wavenumber(f * 1e9), SUB.thickness)
        g = (Y0 - y) / (Y0 + y)
        out.append((f, db(g), deg(g)))
    return out


def lit(obj):
    if isinstance(obj, dict):
        return "{" + ", ".join(f"{lit(k)}: {lit(v)}" for k, v in obj.items()) + "}"
    if isinstance(obj, (list, tuple)):
        return "[" + ", ".join(lit(v) for v in obj) + "]"
    if isinstance(obj, float):
        return repr(round(obj, 6))
    return repr(obj)


