"""Tables, Pareto fronts and figure for the fewer-diodes study. Reads diode_reduction.json and rotated_board_chi0/chi45.json."""
import csv
import json
import os
from pathlib import Path

import numpy as np

R = Path("results/sidequest_hybrid")
TAG = ("_" + os.environ["K4_TAG"]) if os.environ.get("K4_TAG") else ""
SLL_LIM = -12.7
d = json.loads((R / f"diode_reduction{TAG}.json").read_text(encoding="utf-8"))
rows = d["rows"] if isinstance(d, dict) else d
rows = [r for r in rows if "error" not in r]
for ch in (("chi0", "chi45") if not TAG else ()):  # D4 (rotated disc) was not recalibrated
    f = R / f"rotated_board_{ch}.json"
    if f.exists():
        for r in json.loads(f.read_text(encoding="utf-8"))["rows"]:
            r = dict(r)
            r["id"] = "D4" if ch == "chi0" else "D4_chi45"
            rows.append(r)
BASE = {"K2": next(r for r in rows if r["id"] == "base" and r["spec"]["K"] == "K2" and abs(r["spec"]["lam"] - 0.266) < 1e-9),
        "K4b": next(r for r in rows if r["id"] == "base" and r["spec"]["K"] == "K4b" and abs(r["spec"]["lam"] - 0.555) < 1e-9)}


def feasible(r, kn):
    return r["SLL_worst"] <= SLL_LIM and r["gain_mean"] >= BASE[kn]["gain_mean"] - 2.0 and r["diodes"] <= BASE[kn]["diodes"]


def pareto(rs):
    rs = sorted(rs, key=lambda r: (r["diodes"], -r["gain_mean"]))
    front, best = [], -1e9
    for r in rs:
        if r["gain_mean"] > best + 1e-9:
            front.append(r)
            best = r["gain_mean"]
    return front


def fmt(r):
    return "| %s | %s | %d | %d / %d (%d / %d) | %s | %.1f | %.1f | %.1f | %.1f |" % (r["id"], json.dumps({k: v for k, v in r["spec"].items() if k not in ("K", "id", "dphi", "dtheta", "eps", "lam1", "lam2", "cls")}, default=str).replace("|", "/"), r["diodes"],
                                                                        r["lines_x"], r["lines_y"], r["lines_noinv_x"], r["lines_noinv_y"], r["gain"], r["SLL_worst"], r["XPD_min"], r["ap_eff_pct"], r["static_pct"])


out = ["# Fewer diodes — tables (generated by sidequest_diode_reduction_report.py)\n"]
summary = {}
for kn in ("K2", "K4b"):
    rs = [r for r in rows if r["spec"]["K"] == kn]
    out.append(f"\n## {kn}: baseline {BASE[kn]['diodes']} diodes, gain {BASE[kn]['gain_mean']:.2f} dBi, SLL {BASE[kn]['SLL_worst']} dB\n")
    out.append("| idea | parameters | diodes | lines x/y (without inverters) | gain per state [dBi] | worst SLL | XPD | ap.eff [%] | static [%] |\n|---|---|---|---|---|---|---|---|---|")
    out.append(fmt(BASE[kn]))
    ids = sorted({r["id"] for r in rs})
    for i in ids:
        sub = [r for r in rs if r["id"] == i and r["SLL_worst"] <= SLL_LIM]
        for cap in (700, 500, 360):
            c = [r for r in sub if r["diodes"] <= cap and r["diodes"] < BASE[kn]["diodes"]]
            if c:
                out.append(fmt(max(c, key=lambda r: r["gain_mean"])) + f" cap {cap}")
    feas = [r for r in rs if feasible(r, kn)]
    allf = [r for r in rs if r["SLL_worst"] <= SLL_LIM]
    front = pareto(allf)
    summary[kn] = {}
    for cap in (360, 500):
        c = [r for r in feas if r["diodes"] <= cap]
        summary[kn][cap] = max(c, key=lambda r: r["gain_mean"]) if c else None
        if not c:
            c2 = [r for r in allf if r["diodes"] <= cap]
            summary[kn][f"{cap}_closest"] = max(c2, key=lambda r: r["gain_mean"]) if c2 else None
    out.append(f"\n### {kn} Pareto front (SLL <= {SLL_LIM} dB)\n| id | parameters | diodes | lines | gain | SLL | XPD | ap.eff | static |\n|---|---|---|---|---|---|---|---|---|")
    out += [fmt(r) for r in front]
    out.append(f"\nBest with <= 360 diodes (SLL ok, loss <= 2 dB): {fmt(summary[kn][360]) if summary[kn][360] else 'NONE; closest SLL-ok: ' + (fmt(summary[kn]['360_closest']) if summary[kn].get('360_closest') else 'none')}")
    out.append(f"\nBest with <= 500 diodes: {fmt(summary[kn][500]) if summary[kn][500] else 'NONE; closest SLL-ok: ' + (fmt(summary[kn]['500_closest']) if summary[kn].get('500_closest') else 'none')}")
(R / f"diode_reduction_tables{TAG}.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
with open(R / f"diode_reduction_all{TAG}.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh)
    w.writerow(["K", "id", "diodes", "static_pct", "lines_x", "lines_y", "gain_mean", "gain_per_state", "SLL_worst", "XPD_min", "ap_eff_pct", "feasible_SLL"])
    for r in rows:
        w.writerow([r["spec"]["K"], r["id"], r["diodes"], r["static_pct"], r["lines_x"], r["lines_y"], r["gain_mean"], r["gain"], r["SLL_worst"], r["XPD_min"], r["ap_eff_pct"], r["SLL_worst"] <= SLL_LIM])
# figure
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

fig, axs = plt.subplots(1, 2, figsize=(12, 4.6))
marks = {"base": ("k", "o"), "D1": ("tab:blue", "s"), "D2_1x2x": ("tab:orange", "^"), "D2_1x2y": ("tab:orange", "v"), "D2_2x2": ("tab:red", "^"), "D3_one": ("tab:green", "D"), "D3_strict_x": ("tab:olive", "D"),
         "D5": ("tab:purple", "P"), "D6": ("tab:brown", "X"), "D4": ("tab:gray", "*"), "D4_chi45": ("silver", "*")}
for ax, kn in zip(axs, ("K2", "K4b"), strict=True):
    rs = [r for r in rows if r["spec"]["K"] == kn]
    for i in sorted({r["id"] for r in rs}):
        sub = [r for r in rs if r["id"] == i]
        c, m = marks.get(i, ("tab:cyan", "o") if i.startswith("C_") else ("k", "."))
        ok = [r for r in sub if r["SLL_worst"] <= SLL_LIM]
        bad = [r for r in sub if r["SLL_worst"] > SLL_LIM]
        ax.scatter([r["diodes"] for r in ok], [r["gain_mean"] for r in ok], c=c, marker=m, s=28, label=i if i in marks or not i.startswith("C_") else None, alpha=0.9)
        ax.scatter([r["diodes"] for r in bad], [r["gain_mean"] for r in bad], c=c, marker=m, s=14, alpha=0.18)
    allf = [r for r in rs if r["SLL_worst"] <= SLL_LIM]
    fr = pareto(allf)
    ax.plot([r["diodes"] for r in fr], [r["gain_mean"] for r in fr], "k-", lw=1.4, label="Pareto front (SLL ok)")
    b = BASE[kn]
    ax.scatter([b["diodes"]], [b["gain_mean"]], c="red", marker="*", s=180, zorder=5, label="baseline")
    ax.axvspan(150, 360, color="gold", alpha=0.18, label="RIS estimate 150-360")
    ax.axvline(500, color="gray", ls=":")
    ax.axhline(b["gain_mean"] - 2.0, color="gray", ls="--", lw=0.8)
    ax.set_xlabel("diodes"); ax.set_ylabel("mean gain per state [dBi]"); ax.set_title(f"{kn}: gain vs diodes (faint = SLL > {SLL_LIM} dB)")
    ax.set_xlim(0, b["diodes"] * 1.05); ax.grid(alpha=0.3)
axs[1].legend(fontsize=7, ncol=2, loc="lower right")
fig.tight_layout(); fig.savefig(R / f"diode_reduction_pareto{TAG}.png", dpi=140)
(R / f"diode_reduction_summary{TAG}.json").write_text(json.dumps({kn: {str(k): (v if v is None else {a: v[a] for a in ("id", "spec", "diodes", "gain", "gain_mean", "SLL_worst", "XPD_min", "ap_eff_pct", "lines_x", "lines_y", "static_pct")}) for k, v in summary[kn].items()} for kn in summary}, indent=1, default=str), encoding="utf-8", newline="\n")
print("\n".join(out[:1]))
for kn in summary:
    for k, v in summary[kn].items():
        print(kn, k, None if v is None else (v["id"], v["diodes"], v["gain_mean"], v["SLL_worst"]))
