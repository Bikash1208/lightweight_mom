def write_layout_fourhex(cells, out, title):
    out = Path(out)
    with open(out / "layout.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["x_mm", "y_mm", "diameter_mm", "slot_length_mm", "slot_width_mm", "slot_angle_deg", "port"])
        for k in cells:
            w.writerow(
                [
                    f"{k['x_mm']:.3f}",
                    f"{k['y_mm']:.3f}",
                    D_MM,
                    f"{k['slot_L_mm']:.2f}",
                    f"{k['slot_W_mm']:.2f}",
                    f"{k['slot_angle_deg']:.3f}",
                    k["port"],
                ]
            )
    (out / "layout.json").write_text(
        json.dumps(
            {
                "units": "mm",
                "diameter_mm": D_MM,
                "feeds_mm": {str(p): FEEDS[p] for p in FEEDS},
                "board_mm": [BOARD4_X, BOARD4_Y, H_MM],
                "cells": cells,
            }
        )
    , encoding="utf-8", newline="\n")
    try:
        import ezdxf

        doc = ezdxf.new("R2010")
        for lay in ("PATCH", "SLOT", "OUTLINE"):
            doc.layers.add(lay)
        msp = doc.modelspace()
        for k in cells:
            msp.add_circle((k["x_mm"], k["y_mm"]), D_MM / 2, dxfattribs={"layer": "PATCH"})
            msp.add_lwpolyline(
                slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"]),
                close=True,
                dxfattribs={"layer": "SLOT"},
            )
        for p in FEEDS:
            msp.add_lwpolyline([tuple(v) for v in hex_poly_mm(FEEDS[p])], close=True, dxfattribs={"layer": "OUTLINE"})
        doc.saveas(out / "layout.dxf")
    except Exception as exc:  # noqa: BLE001
        (out / "layout.dxf.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n", encoding="utf-8", newline="\n")
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(11, 9))
        col = {1: "#d9a441", 2: "#6a9fd1", 3: "#8cc08c", 4: "#d98a8a"}
        for k in cells:
            ax.add_patch(plt.Circle((k["x_mm"], k["y_mm"]), D_MM / 2, fc=col[k["port"]], ec="none"))
            ax.add_patch(
                plt.Polygon(
                    slot_corners(k["x_mm"], k["y_mm"], k["slot_L_mm"], k["slot_W_mm"], k["slot_angle_deg"]),
                    fc="white",
                    ec="none",
                )
            )
        for p in FEEDS:
            ax.add_patch(plt.Polygon(hex_poly_mm(FEEDS[p]), fc="none", ec="k", ls="--"))
            ax.plot(*FEEDS[p], "r+", ms=12)
            ax.annotate(f"port {p}", FEEDS[p], xytext=(5, 8), textcoords="offset points", color="r")
        ax.set_aspect("equal")
        ax.set_xlim(-335, 335)
        ax.set_ylim(-275, 275)
        ax.set_title(title)
        fig.savefig(out / "layout.png", dpi=100)
    except Exception as exc:  # noqa: BLE001
        (out / "layout.png.NOT_WRITTEN.txt").write_text(f"{type(exc).__name__}: {exc}\n", encoding="utf-8", newline="\n")


