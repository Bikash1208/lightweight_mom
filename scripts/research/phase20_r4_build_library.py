"""Phase 20 R4 item 3: build the CP-2 state library by CHUNKS (one file per frequency, written atomically, skipped when present: re-running the same command resumes
after an interruption, a sleep or a clock jump). MODEL_ONLY, NOT_HFSS_VALIDATED, PROVISIONAL_DATASHEET.

    python scripts/research/phase20_r4_build_library.py grid            # mesh 60, 41 f x (theta, phi) points, 11 workers
    python scripts/research/phase20_r4_build_library.py corr60|corr90|corr120   # the correction set (17 f x 7 points) at the named mesh
    python scripts/research/phase20_r4_build_library.py status

Grid: f = 8.0-12.0 GHz step 0.1; theta = 0, 5, ..., 45 deg; phi = 0, 15, ..., 345 deg (theta = 0: the phi = 0 point only; the rest follows by the exact frame rotation at assembly);
four one-hot states per point (one shared impedance matrix). Correction set: f = 8.0, 8.25, ..., 12.0 GHz; (theta, phi) in {(0, 0)} + {15, 30, 45} x {0, 90} deg.
Chunks go to `results/phase20_r4/chunks/` (git-ignored, regenerated by this script); no timing here uses the wall clock (monotonic only).
"""

import os
import sys

for _k in ("OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_k, "1")

import json  # noqa: E402
import math  # noqa: E402
import time  # noqa: E402
import warnings  # noqa: E402
from multiprocessing import Pool  # noqa: E402
from pathlib import Path  # noqa: E402

import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts" / "research"))

CHUNKS = ROOT / "results" / "phase20_r4" / "chunks"
PARAMS_JSON = ROOT / "results" / "phase20_r3" / "opt" / "cp2_madp_final.json"

GRID_F = [
    8.0 + 0.25 * i for i in range(17)
]  # reduced grid (R4 finding: F = 2n costs ~2x per point and ~8x at mesh 120)
GRID_THETA = [7.5 * i for i in range(7)]
GRID_PHI = [30.0 * i for i in range(12)]
CORR_F = [8.0 + 0.5 * i for i in range(9)]
CORR_POINTS = [(0.0, 0.0)] + [(th, ph) for th in (30.0, 45.0) for ph in (0.0, 90.0)]
GRID_MESH = 60


def floquet_order(n):
    """Floquet cutoff for a mesh of n cells per period: 2n. The solver's minimum (2F + 1 >= n) and even 0.67 n or 0.83 n leave isolated numerical lines (narrow
    spurious resonances that move with F: e.g. 10.607 GHz at theta 10, phi 45 for mesh 60 / F 60); at mesh 60 the results at F = 120 and F = 150 agree to < 1 degree, F = 90 is
    still off by up to 11 degrees at one frequency of the scan (R4 finding, results/phase20_r4/FLOQUET_CONVERGENCE.md)."""
    return 2 * n


def grid_points():
    return [(0.0, 0.0)] + [(th, ph) for th in GRID_THETA[1:] for ph in GRID_PHI]


_STATE = {}


def _setup():
    if not _STATE:
        from phase20_r3_finalist import build

        from src.excitation import ReferencePlanes
        from src.ris.cells import madp_kit

        d = json.loads(PARAMS_JSON.read_text())
        cell = build("cp2", d["params_mm"], d["period_mm"])
        kit = madp_kit()
        _STATE["sets"] = [cell.unit_cell(st, kit).loads for st in cell.states()]
        _STATE["base"] = cell.unit_cell(cell.states()[0], kit)
        _STATE["planes"] = ReferencePlanes(0.0, None, 1.575e-3)
    return _STATE


def solve_point(args):
    """(f_ghz, theta_deg, phi_deg, mesh) -> (4, 2, 2) complex TE/TM reflection of the four states. Mesh-120 points are cached one file each (a chunk takes hours; a
    failed or restarted chunk must not redo finished points)."""
    f, th, ph, n, *rest = args
    cache = CHUNKS / "points" / f"m{n}_f{f:.2f}_t{th:g}_p{ph:g}.npy" if n >= 120 and not rest else None
    if cache is not None and cache.exists():
        return np.load(cache)
    out = _solve_point(args)
    if cache is not None:
        cache.parent.mkdir(exist_ok=True)
        tmp = cache.with_name("." + cache.name + ".partial.npy")
        np.save(tmp, out)
        os.replace(tmp, cache)
    return out


def _solve_point(args):
    from src.basis_functions import MeshSettings
    from src.sparameters import compute_s_parameters_oblique_over_loads

    f, th, ph, n, *rest = args
    fl = (
        rest[0] if rest else floquet_order(n)
    )  # optional explicit Floquet cutoff (validation references use a larger one)
    st = _setup()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = compute_s_parameters_oblique_over_loads(
            st["base"],
            f * 1e9,
            MeshSettings(n, n, fl),
            st["planes"],
            math.radians(th),
            math.radians(ph),
            st["sets"],
            warn_grating=False,
        )
    return np.array([r.s11 for r in res])


def chunk_path(kind, f):
    return CHUNKS / f"{kind}_f{f:.2f}.npz"


def save_atomic(path, **arrays):
    """Write `path` atomically and durably: temp file (hidden name, never matched by a `grid_f*.npz` glob), flush + fsync, then `os.replace`."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.partial")
    with open(tmp, "wb") as fh:
        np.savez(fh, **arrays)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


def chunk_ok(kind, f, mesh, points):
    """True only for a complete, loadable chunk of the right mesh and point list (a zero-length or truncated file after a crash is rebuilt)."""
    path = chunk_path(kind, f)
    if not path.exists():
        return False
    try:
        z = np.load(path)
        return (
            int(z["mesh"]) == mesh
            and np.allclose(z["points"], np.array(points))
            and z["s"].shape == (len(points), 4, 2, 2)
            and bool(np.isfinite(z["s"]).all())
        )
    except Exception:
        return False


TIMEOUT_S = {
    "grid": 1800,
    "corr60": 600,
    "corr90": 2400,
    "corr120": 6 * 3600,
}  # per chunk; a dead worker (e.g. out-of-memory kill) otherwise hangs pool.map forever


def run(kind, workers, reverse=False, only=None):
    mesh = {"grid": GRID_MESH, "corr60": 60, "corr90": 90, "corr120": 120}[kind]
    freqs = GRID_F if kind == "grid" else CORR_F
    pts = grid_points() if kind == "grid" else CORR_POINTS
    todo = [f for f in freqs if not chunk_ok(kind, f, mesh, pts)]
    if only is not None:  # explicit frequencies for an extra builder process
        todo = [f for f in todo if any(abs(f - o) < 1e-9 for o in only)]
    if reverse:  # a second builder process works from the other end (memory permitting); chunks are atomic so a meeting-point duplicate is harmless
        todo.reverse()
    print(
        f"{kind}: {len(freqs) - len(todo)}/{len(freqs)} valid chunks present, {len(todo)} to do, mesh {mesh}, {workers} workers",
        flush=True,
    )
    t0 = time.monotonic()
    pool = Pool(workers)
    try:
        for f in todo:
            if chunk_ok(kind, f, mesh, pts):  # finished meanwhile by another builder process
                continue
            for attempt in range(3):
                try:
                    res = pool.map_async(solve_point, [(f, th, ph, mesh) for th, ph in pts], chunksize=1).get(
                        timeout=TIMEOUT_S[kind]
                    )
                    break
                except (
                    Exception
                ) as e:  # timeout (hung / killed worker) or a worker exception: rebuild the pool and retry this chunk
                    print(
                        f"  f = {f:.2f}: attempt {attempt + 1} failed ({type(e).__name__}); restarting the pool",
                        flush=True,
                    )
                    pool.terminate()
                    pool = Pool(workers)
            else:
                raise RuntimeError(f"chunk f = {f:.2f} GHz failed 3 times")
            save_atomic(chunk_path(kind, f), f_ghz=f, points=np.array(pts), s=np.array(res), mesh=mesh)
            print(f"  f = {f:.2f} GHz done ({time.monotonic() - t0:.0f} s)", flush=True)
    finally:
        pool.terminate()


def status():
    for kind, freqs, mesh, pts in (
        ("grid", GRID_F, GRID_MESH, grid_points()),
        ("corr60", CORR_F, 60, CORR_POINTS),
        ("corr90", CORR_F, 90, CORR_POINTS),
        ("corr120", CORR_F, 120, CORR_POINTS),
    ):
        have = sum(chunk_ok(kind, f, mesh, pts) for f in freqs)
        print(f"{kind}: {have}/{len(freqs)}")


def _lin(start, step, stop, endpoint):
    n = round((stop - start) / step)
    return [start + step * i for i in range(n + 1 if endpoint else n)]


def configure_grid(f_step=None, theta_step=None, phi_step=None, f_list=None, theta_list=None, phi_list=None):
    """Override the grid constants (f 8-12 GHz, theta 0-45 deg, phi 0-<360 deg) by a step or an explicit list; an argument left at None keeps the current constant, so
    `configure_grid()` changes nothing. With the default steps (0.25 GHz, 7.5 deg, 30 deg) the lists equal the constants above exactly."""
    global GRID_F, GRID_THETA, GRID_PHI
    if f_list is not None:
        GRID_F = list(f_list)
    elif f_step is not None:
        GRID_F = _lin(8.0, f_step, 12.0, True)
    if theta_list is not None:
        GRID_THETA = list(theta_list)
    elif theta_step is not None:
        GRID_THETA = _lin(0.0, theta_step, 45.0, True)
    if phi_list is not None:
        GRID_PHI = list(phi_list)
    elif phi_step is not None:
        GRID_PHI = _lin(0.0, phi_step, 360.0, False)


def parse_grid_options(argv):
    """Pull the optional `--f-step/--theta-step/--phi-step X`, `--f-list/--theta-list/--phi-list a,b,c` and `--dry-run` out of argv; returns (positional, kwargs, dry_run)."""
    keys = {"--f-step": "f_step", "--theta-step": "theta_step", "--phi-step": "phi_step"}
    lists = {"--f-list": "f_list", "--theta-list": "theta_list", "--phi-list": "phi_list"}
    pos, kw, dry, i = [], {}, False, 0
    while i < len(argv):
        a = argv[i]
        if a == "--dry-run":
            dry = True
        elif a in keys:
            kw[keys[a]] = float(argv[i + 1])
            i += 1
        elif a in lists:
            kw[lists[a]] = [float(x) for x in argv[i + 1].split(",")]
            i += 1
        else:
            pos.append(a)
        i += 1
    return pos, kw, dry


if __name__ == "__main__":
    argv, grid_kw, dry_run = parse_grid_options(sys.argv)
    configure_grid(**grid_kw)
    if dry_run:
        print(
            json.dumps(
                {
                    "GRID_F": GRID_F,
                    "GRID_THETA": GRID_THETA,
                    "GRID_PHI": GRID_PHI,
                    "n_points_per_f": len(grid_points()),
                    "n_tasks": len(GRID_F) * len(grid_points()),
                }
            )
        )
        sys.exit(0)
    sys.argv = argv
    cmd = sys.argv[1]
    if cmd == "status":
        status()
    else:
        w = int(sys.argv[2]) if len(sys.argv) > 2 else {"grid": 11, "corr60": 11, "corr90": 4, "corr120": 2}[cmd]
        arg = sys.argv[3] if len(sys.argv) > 3 else ""
        only = [float(x) for x in arg[5:].split(",")] if arg.startswith("only:") else None
        run(cmd, w, reverse=arg == "reverse", only=only)
