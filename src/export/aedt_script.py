"""Phase 21 D2: the AEDT (HFSS) IronPython build script for a multi-port board, generated from an
`ExactBoard` -- exact millimetre values written as plain decimals, so there is no STEP import and no
1.99999 dimension. Ported from `scripts/adhoc/square4/aedt_template.py` (the hand-built reference),
generalised to rectangles of any size, any substrate and any frequency.

The script builds the substrate, a ground sheet with a coax opening at every feed, the patches united
into one body "Patches" (Perfect E), PEC monopoles, 50 ohm lumped ports on the coax annulus, an air box
with a radiation boundary, a driven-modal setup, an interpolating sweep and a 1 degree far-field sphere.
Design variables: mono_h, r_pin, r_out, pad_xy, pad_top, pad_bot. It runs in AEDT (Tools > Run Script)."""

from .exact_board import DEFAULT_MONO_H_MM, DEFAULT_R_PIN_MM, fmt, quantize

DEFAULT_R_OUT_MM = "2.05"

_TEMPLATE = r'''
# -*- coding: utf-8 -*-
# HFSS (AEDT) IronPython script -- @@N_PORTS@@-port HMSA board "@@NAME@@" (generated by lwmom).
# Run inside AEDT: Tools > Run Script... (works in AEDT 2019 R1 and later; IronPython 2.7 or CPython).
# Builds everything natively with exact millimetre values, so no STEP import and no 1.99999 dimensions.
#
#   Substrate  eps_r @@EPS_R@@, tan d @@TAND@@ (material "HMSA_substrate"), @@W@@ x @@HT@@ x @@H@@ mm, z = 0 .. @@H@@ mm
#   Ground     PEC sheet at z = 0 with a coax opening (radius r_out) at each feed
#   Patches    @@N@@ rectangles at z = @@H@@ mm, united into one sheet, Perfect E
#   Monopoles  PEC pins (radius r_pin, height mono_h from the ground), one per port
#   Ports      lumped ports on the coax annulus at z = 0 (r_pin .. r_out), 50 ohm
#   Air        box padded by pad_xy / pad_top / pad_bot, radiation boundary
#   Setup      @@F_GHZ@@ GHz driven modal + optional sweep; far-field sphere 1 deg
#
# Edit the design variables (mono_h, r_pin, ...) in HFSS after the build to match your monopole.
import ScriptEnv
ScriptEnv.Initialize("Ansoft.ElectronicsDesktop")
oDesktop.RestoreWindow()
oProject = oDesktop.NewProject()
oProject.InsertDesign("HFSS", "@@NAME@@", "DrivenModal", "")
oDesign = oProject.SetActiveDesign("@@NAME@@")
oEditor = oDesign.SetActiveEditor("3D Modeler")
oEditor.SetModelUnits(["NAME:Units Parameter", "Units:=", "mm", "Rescale:=", False])

BUILD_MONOPOLES = True      # False: geometry only (patches, substrate, ground), no feeds or ports
ADD_SWEEP = True            # @@SWEEP_LO@@ - @@SWEEP_HI@@ GHz interpolating sweep in addition to the @@F_GHZ@@ GHz solve

H = "@@H@@mm"
WX = "@@W@@mm"; WY = "@@HT@@mm"      # board size
CX = "@@CX@@mm"; CY = "@@CY@@mm"      # board centre
FEEDS = [@@FEEDS@@]   # (x, y) mm, ports 1..@@N_PORTS@@
PATCHES = [  # (x, y, width, height) mm: lower-left corner and size of every patch
@@PATCHES@@
]

# substrate material (defined here so the script does not depend on a material library)
oProject.GetDefinitionManager().AddMaterial(["NAME:HMSA_substrate", "CoordinateSystemType:=", "Cartesian",
    "BulkOrSurfaceType:=", 1, ["NAME:PhysicsTypes", "set:=", ["Electromagnetic"]],
    "permittivity:=", "@@EPS_R@@", "dielectric_loss_tangent:=", "@@TAND@@"])

def var(name, value):
    oDesign.ChangeProperty(["NAME:AllTabs", ["NAME:LocalVariableTab",
        ["NAME:PropServers", "LocalVariables"],
        ["NAME:NewProps", ["NAME:" + name, "PropType:=", "VariableProp", "UserDef:=", True, "Value:=", value]]]])

for n, v in (("mono_h", "@@MONOH@@mm"), ("r_pin", "@@RPIN@@mm"), ("r_out", "@@ROUT@@mm"),
             ("pad_xy", "15mm"), ("pad_top", "30mm"), ("pad_bot", "15mm")):
    var(n, v)

def attrs(name, material, solve_inside, color="(255 128 0)", transp=0):
    return ["NAME:Attributes", "Name:=", name, "Flags:=", "", "Color:=", color, "Transparency:=", transp,
            "PartCoordinateSystem:=", "Global", "UDMId:=", "", "MaterialValue:=", '"' + material + '"',
            "SurfaceMaterialValue:=", '""', "SolveInside:=", solve_inside, "IsMaterialEditable:=", True,
            "UseMaterialAppearance:=", False, "IsLightweight:=", False]

def mm(v):
    return repr(v) + "mm" if isinstance(v, float) else str(v) + "mm"

def rect(name, x, y, z, w, h, color="(255 128 0)"):
    oEditor.CreateRectangle(["NAME:RectangleParameters", "IsCovered:=", True,
        "XStart:=", x, "YStart:=", y, "ZStart:=", z, "Width:=", w, "Height:=", h, "WhichAxis:=", "Z"],
        attrs(name, "vacuum", True, color))

def circle(name, x, y, z, r):
    oEditor.CreateCircle(["NAME:CircleParameters", "IsCovered:=", True, "XCenter:=", x, "YCenter:=", y,
        "ZCenter:=", z, "Radius:=", r, "WhichAxis:=", "Z", "NumSegments:=", "0"], attrs(name, "vacuum", True))

def unite(names):
    oEditor.Unite(["NAME:Selections", "Selections:=", ",".join(names)], ["NAME:UniteParameters", "KeepOriginals:=", False])

def subtract(blank, tools, keep):
    oEditor.Subtract(["NAME:Selections", "Blank Parts:=", blank, "Tool Parts:=", ",".join(tools)],
                     ["NAME:SubtractParameters", "KeepOriginals:=", keep])

x_lo = "(" + CX + "-" + WX + "/2)"; y_lo = "(" + CY + "-" + WY + "/2)"
# substrate
oEditor.CreateBox(["NAME:BoxParameters", "XPosition:=", x_lo, "YPosition:=", y_lo, "ZPosition:=", "0mm",
    "XSize:=", WX, "YSize:=", WY, "ZSize:=", H], attrs("Substrate", "HMSA_substrate", True, "(0 128 0)", 0.6))
# ground
rect("Ground", x_lo, y_lo, "0mm", WX, WY, "(128 128 128)")
# patches, united in blocks of 100 then into one body
names = []
for k, (x, y, pw, ph) in enumerate(PATCHES):
    nm = "P%d" % k
    rect(nm, mm(x), mm(y), H, mm(pw), mm(ph))
    names.append(nm)
blocks = []
for b in range(0, len(names), 100):
    grp = names[b:b + 100]
    if len(grp) > 1:
        unite(grp)
    blocks.append(grp[0])
if len(blocks) > 1:
    unite(blocks)
oEditor.ChangeProperty(["NAME:AllTabs", ["NAME:Geometry3DAttributeTab", ["NAME:PropServers", names[0]],
    ["NAME:ChangedProps", ["NAME:Name", "Value:=", "Patches"]]]])

oBnd = oDesign.GetModule("BoundarySetup")
if BUILD_MONOPOLES:
    pins = []; holes = []
    for k, (x, y) in enumerate(FEEDS):
        p = k + 1
        oEditor.CreateCylinder(["NAME:CylinderParameters", "XCenter:=", mm(x), "YCenter:=", mm(y), "ZCenter:=", "0mm",
            "Radius:=", "r_pin", "Height:=", "mono_h", "WhichAxis:=", "Z", "NumSides:=", "0"],
            attrs("Monopole%d" % p, "pec", False, "(255 255 0)"))
        pins.append("Monopole%d" % p)
        circle("Hole%d" % p, mm(x), mm(y), "0mm", "r_out"); holes.append("Hole%d" % p)
        circle("PortSheet%d" % p, mm(x), mm(y), "0mm", "r_out")
        circle("PinCut%d" % p, mm(x), mm(y), "0mm", "r_pin")
        subtract("PortSheet%d" % p, ["PinCut%d" % p], False)
    subtract("Ground", holes, False)
    subtract("Substrate", pins, True)
    for k, (x, y) in enumerate(FEEDS):
        p = k + 1
        oBnd.AssignLumpedPort(["NAME:Port%d" % p, "Objects:=", ["PortSheet%d" % p], "DoDeembed:=", False,
            "RenormalizeAllTerminals:=", True,
            ["NAME:Modes", ["NAME:Mode1", "ModeNum:=", 1, "UseIntLine:=", True,
                ["NAME:IntLine", "Start:=", [mm(x) + "+r_pin", mm(y), "0mm"], "End:=", [mm(x) + "+r_out", mm(y), "0mm"]],
                "AlignmentGroup:=", 0, "CharImp:=", "Zpi", "RenormImp:=", "50ohm"]],
            "ShowReporterFilter:=", False, "ReporterFilter:=", [True], "Impedance:=", "50ohm"])

oBnd.AssignPerfectE(["NAME:PerfE_Ground", "Objects:=", ["Ground"], "InfGroundPlane:=", False])
oBnd.AssignPerfectE(["NAME:PerfE_Patches", "Objects:=", ["Patches"], "InfGroundPlane:=", False])

# air box + radiation
oEditor.CreateBox(["NAME:BoxParameters", "XPosition:=", x_lo + "-pad_xy", "YPosition:=", y_lo + "-pad_xy",
    "ZPosition:=", "-pad_bot", "XSize:=", WX + "+2*pad_xy", "YSize:=", WY + "+2*pad_xy",
    "ZSize:=", "pad_bot+" + H + "+pad_top"], attrs("Air", "air", True, "(143 175 143)", 0.9))
oBnd.AssignRadiation(["NAME:Rad1", "Objects:=", ["Air"], "IsFssReference:=", False, "IsForPML:=", False])

oAna = oDesign.GetModule("AnalysisSetup")
oAna.InsertSetup("HfssDriven", ["NAME:Setup1", "Frequency:=", "@@F_GHZ@@GHz", "MaxDeltaS:=", 0.02,
    "MaximumPasses:=", 15, "MinimumPasses:=", 2, "MinimumConvergedPasses:=", 2, "PercentRefinement:=", 30,
    "IsEnabled:=", True, "BasisOrder:=", 1, "DoLambdaRefine:=", True, "DoMaterialLambda:=", True,
    "SetLambdaTarget:=", False, "Target:=", 0.3333, "UseMaxTetIncrease:=", False])
if ADD_SWEEP:
    oAna.InsertFrequencySweep("Setup1", ["NAME:Sweep", "IsEnabled:=", True, "RangeType:=", "LinearStep",
        "RangeStart:=", "@@SWEEP_LO@@GHz", "RangeEnd:=", "@@SWEEP_HI@@GHz", "RangeStep:=", "0.02GHz", "Type:=", "Interpolating",
        "SaveFields:=", False, "SaveRadFields:=", False, "InterpTolerance:=", 0.5, "InterpMaxSolns:=", 250,
        "InterpMinSolns:=", 0, "InterpMinSubranges:=", 1])
oRad = oDesign.GetModule("RadField")
oRad.InsertFarFieldSphereSetup(["NAME:3D", "UseCustomRadiationSurface:=", False,
    "ThetaStart:=", "0deg", "ThetaStop:=", "90deg", "ThetaStep:=", "0.5deg",
    "PhiStart:=", "0deg", "PhiStop:=", "360deg", "PhiStep:=", "1deg", "UseLocalCS:=", False])
oEditor.FitAll()
oProject.SaveAs(oDesktop.GetProjectDirectory() + "/@@NAME@@.aedt", True)
oDesktop.AddMessage(oProject.GetName(), "@@NAME@@", 0, "Built: @@N@@ patches, @@N_PORTS@@ monopoles, @@N_PORTS@@ lumped ports. Validate, then Analyze All.")

'''.lstrip("\n")


def generate_aedt_script(board, name, eps_r, tan_delta, frequency_hz, r_pin_mm=DEFAULT_R_PIN_MM, r_out_mm=DEFAULT_R_OUT_MM,
                       mono_h_mm=DEFAULT_MONO_H_MM):
    """The script text. `name` becomes the HFSS design and project name (letters, digits, _)."""
    safe = "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)
    f_ghz = frequency_hz / 1e9
    patches = ",\n".join(
        "(%s,%s,%s,%s)" % (fmt(p.x0), fmt(p.y0), fmt(p.x1 - p.x0), fmt(p.y1 - p.y0)) for p in board.patches
    )
    feeds = ", ".join("(%s,%s)" % (fmt(x), fmt(y)) for x, y in board.feeds_mm)
    values = {
        "NAME": safe,
        "N_PORTS": str(len(board.feeds_mm)),
        "EPS_R": repr(float(eps_r)),
        "TAND": repr(float(tan_delta)),
        "W": fmt(board.width_mm),
        "HT": fmt(board.height_mm),
        "H": fmt(board.thickness_mm),
        "CX": fmt((board.x_min + board.x_max) / 2),
        "CY": fmt((board.y_min + board.y_max) / 2),
        "F_GHZ": "%g" % f_ghz,
        "SWEEP_LO": "%g" % round(0.95 * f_ghz, 2),
        "SWEEP_HI": "%g" % round(1.05 * f_ghz, 2),
        "RPIN": fmt(quantize(r_pin_mm)),
        "MONOH": fmt(quantize(mono_h_mm)),
        "ROUT": fmt(quantize(r_out_mm)),
        "N": str(len(board.patches)),
        "FEEDS": feeds,
        "PATCHES": patches,
    }
    text = _TEMPLATE
    for key, value in values.items():
        text = text.replace("@@%s@@" % key, value)
    return text
