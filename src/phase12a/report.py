"""Render ``phase12a_report.md`` (results folder) from an already-computed ``Phase12aResult``."""

from ..sparameters import SURFACE_WAVE_TOLERANCE_RTOL


def render_phase12a_report_md(result):
    d = result.decision
    cov = result.coverage_by_frequency[result.design_frequency_hz]
    ug = result.ungrounded_comparison
    conv = result.convergence_points
    sw = result.surface_wave_points
    max_sw_margin = min(p.nearest_margin_over_k0 for p in sw)
    any_sw_in_band = any(p.any_in_band for p in sw)

    if ug.get("status") == "AVAILABLE":
        ug_lines = (
            f"- Ungrounded Phase 7 library at {ug['frequency_hz'] / 1e9:.3f} GHz: "
            f"S11_xx coverage = {ug['S11_xx']['coverage_deg']:.2f} deg "
            f"(largest gap {ug['S11_xx']['largest_gap_deg']:.2f} deg, {ug['S11_xx']['n_points']} cells), "
            f"S21_xx coverage = {ug['S21_xx']['coverage_deg']:.2f} deg."
        )
    else:
        ug_lines = "- Ungrounded Phase 7 comparison: `NOT_AVAILABLE_FROM_CURRENT_DATA` (checkpoint not present)."

    conv_lines = "\n".join(
        f"  - {p.cells_per_side}x{p.cells_per_side} cells, floquet_order={p.floquet_order}: "
        f"|S11_xx|={p.s11_xx_mag:.6f}, phase={p.s11_xx_phase_deg:.3f} deg"
        for p in conv
    )

    return f"""# Phase 12A report — PEC ground plane (grounded-substrate stack)

Generated by `examples/run_phase12a_ground_plane.py` / `src/phase12a/run.py`. No ML/surrogate
anywhere in this phase: every number below is a direct MoM solve (`src/sparameters.py`,
`compute_s_parameters`, unmodified except for the additive one-port/`backing="pec"` code path)
or a closed-form/analytic check against it.

## 1. Final status

```
Grounded-stack status:   {d.status}
Reason:                  {d.reason}
HFSS status:             {d.hfss_status}
Geometry inversion:      {d.geometry_inversion_status}
STEP export:             {d.step_export_status}
```

## 2. Physics-sanity sweep (Phase 7's own substrate/period/mesh, L = W, grounded)

At the design frequency ({result.design_frequency_hz / 1e9:.3f} GHz): S11_xx circular phase
coverage = **{cov.coverage_deg:.2f} deg** (largest gap {cov.largest_gap_deg:.2f} deg,
{cov.n_points} points, L = 1.0-4.4 mm in 0.2 mm steps -- the same 18 values Phase 7 swept).

{ug_lines}

{"Coverage is far from 360 degrees; a larger/smaller substrate thickness or a different topology is the next question, not this phase's to answer (brief Sec. 'Physics sanity')." if cov.coverage_deg < 360.0 else ""}

See `plots/phase_vs_length.png`, `plots/magnitude_vs_length.png`,
`plots/grounded_vs_ungrounded.png`.

## 3. Analytic grounded-slab validation

Bare (unpatterned) grounded slab vs the textbook closed form
`Gamma = (j eta_s tan(k_s h) - eta0) / (j eta_s tan(k_s h) + eta0)`, lossless and lossy, across
10-15 GHz: maximum disagreement = **{result.max_analytic_error:.3g}** (solver floating-point
noise floor). `h -> 0` limit: Gamma = {result.thin_limit.real:.6f} {result.thin_limit.imag:+.2e}j
(-> -1 as expected).

## 4. Surface-wave-pole proximity (TM0, no cutoff)

For the 4.8 mm (Phase 7 library) and 8 mm (original Phase 1-6) periods, at 10-15 GHz, normal
incidence: no Floquet harmonic used in the impedance-matrix assembly falls inside, or within the
{SURFACE_WAVE_TOLERANCE_RTOL:.0%} tolerance of, the TM0 surface-wave interval
`(k0, Re(k_substrate))` in any tested case (`any_in_band = {any_sw_in_band}`); the smallest
measured margin to the interval's edge is **{max_sw_margin:.3g} x k0** (i.e. the nearest harmonic
sits a full k0 or more away — see `surface_wave_pole.json` for every (period, frequency) point).

## 5. Mesh/Floquet convergence (one representative grounded patch, C3 = 2.8x2.8 mm)

`discretization.refinement_study` (Phase 7's own 32x32/floquet=32 mesh as the base):
`floquet_error = {result.floquet_error:.4g}`, `mesh_error = {result.mesh_error:.4g}`
(tolerance {result.mesh_floquet_tolerance:g}). Supplementary raw sweep (mesh and Floquet order
doubled together, not Phase 7's own mesh choice):
{conv_lines}

{"Convergence is not monotonic at coarse mesh -- a real, measured finding: grounded/near-resonant patches are noticeably more mesh-sensitive than the ungrounded scattering patches this mesh/sweep-step combination was originally chosen for (library_schema.py). This is honestly reported here, not smoothed over." if result.mesh_error > result.mesh_floquet_tolerance else ""}

## 6. Regression: the ungrounded stack is unaffected

All pre-existing tests pass with no changes to their expectations (see the project-wide test
count in `PHASE12A_GROUND_PLANE.md`); the default (`backing="air"`, or no `backing` key at all)
code path is verified bit-identical to before Phase 12A for `LayeredGreenFunction.spectral_dyad`
and `.stack_fields`.

## 7. Independent verification

`tests/reference_layered.py` (a 3-D plane-wave field-matching solver sharing no derivation with
`src/green_function.py`) was extended with a PEC-terminated variant
(`solve_current_sheet_grounded`, `solve_incident_fields_grounded`) and agrees with the kernel to
~1e-14 across normal/oblique incidence, lossy/lossless substrates, and multiple periods/thicknesses
(`tests/test_green_function_grounded.py`).
"""
